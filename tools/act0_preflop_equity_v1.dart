// Rebuild the checked-in table from the live chart:
// dart run tools/act0_preflop_equity_v1.dart
// A host C++17 compiler is needed for this offline tool and its regression.
import 'dart:convert';
import 'dart:io';

import '../lib/ui_v2/act0_shell/act0_starting_chart_v1.dart';

const act0EquityOpeningSeatsV1 = [Act0ChartSeatV1.co, Act0ChartSeatV1.btn];

Future<Map<String, ({int halfShares, int deals})>> enumeratePreflopEquityV1(
  Iterable<String> range, {
  Iterable<String> directHands = const [],
}) async {
  final temp = await Directory.systemTemp.createTemp('act0_preflop_equity_');
  try {
    final executable = '${temp.path}/equity';
    final compile = await Process.run('c++', [
      '-O3',
      '-std=c++17',
      'tools/act0_preflop_equity_v1.cpp',
      '-o',
      executable,
    ]);
    if (compile.exitCode != 0) throw StateError('${compile.stderr}');
    final worker = await Process.start(executable, []);
    worker.stdin.writeln(range.length);
    worker.stdin.writeln(range.join(' '));
    worker.stdin.writeln(directHands.join(' '));
    await worker.stdin.close();
    final output = await worker.stdout.transform(utf8.decoder).join();
    final errors = await worker.stderr.transform(utf8.decoder).join();
    if (await worker.exitCode != 0) throw StateError(errors);
    final counts = <String, ({int halfShares, int deals})>{};
    for (final line in LineSplitter.split(output)) {
      final [hand, shares, deals] = line.split(' ');
      counts[hand] = (halfShares: int.parse(shares), deals: int.parse(deals));
    }
    return counts;
  } finally {
    await temp.delete(recursive: true);
  }
}

Future<void> main() async {
  final ranges = {
    for (final seat in act0EquityOpeningSeatsV1)
      act0ChartHandsV1
          .where(
            (hand) =>
                act0ChartActionV1(hand, seat, Act0ChartPrefixV1.unopened) ==
                Act0ChartActionV1.raise,
          )
          .join(','),
  };
  final source = StringBuffer('''
  // Generated by tools/act0_preflop_equity_v1.dart from the chart.
  // Values are in tenths of a percentage point, in act0ChartHandsV1 order.
  const act0PreflopEquityByOpeningRangeV1 = <String, List<int>>{
  ''');
  for (final key in ranges) {
    final counts = await enumeratePreflopEquityV1(key.split(','));
    if (counts.length != act0ChartHandsV1.length) {
      throw StateError('The table does not cover 169 hand classes.');
    }
    source.writeln("  '$key': [");
    for (final hand in act0ChartHandsV1) {
      final count = counts[hand]!;
      final equity = (500 * count.halfShares / count.deals).round();
      source.writeln('    $equity, // $hand');
    }
    source.writeln('  ],');
  }
  source.writeln('};');
  final file = File('lib/ui_v2/act0_shell/act0_preflop_equity_table_v1.g.dart');
  file.writeAsStringSync(source.toString());
  final format = await Process.run(Platform.resolvedExecutable, [
    'format',
    file.path,
  ]);
  if (format.exitCode != 0) throw StateError('${format.stderr}');
}
